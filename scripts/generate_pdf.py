# Available width for tables and images
PAGE_W, PAGE_H = A4
LEFT_M = RIGHT_M = 22*mm
TOP_M = 22*mm
BOTTOM_M = 22*mm
CONTENT_W = PAGE_W - LEFT_M - RIGHT_M

def embed_image(path, max_width=None, max_height=None):
    if max_width is None:
        max_width = CONTENT_W
    if max_height is None:
        max_height = PAGE_H * 0.40
    pil = PILImage.open(path)
    ow, oh = pil.size
    rw = max_width / ow if ow > max_width else 1.0
    rh = max_height / oh if oh > max_height else 1.0
    r = min(rw, rh)
    return Image(path, width=ow*r, height=oh*r)

def fig_block(path, caption_text, max_height=None):
    img = embed_image(path, max_height=max_height)
    return KeepTogether([img, caption(caption_text)])

